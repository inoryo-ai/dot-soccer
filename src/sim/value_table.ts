/**
 * ボールを持っていることの価値の表（D-44）。**このファイルは手で書かない。**
 *
 *     node scripts/build_value_table.ts      # 試合を回して作り直す（いまのAIで数回くり返す）
 *
 * 🔑 中身は「その場所でボールを持っていた攻撃が、そのあと撃ったシュートの入る確率の合計」の平均
 *    （現実の xT＝期待脅威と同じ作り方を、このゲームの試合で行う）。
 *    まっすぐ運んで撃つ1本の道だけを見る見積もり（D-42）では、たまたま一直線上が空いた遠い位置が
 *    高く見え、ゴール前から後ろへ戻すパスを選んだ。実際の結果から作れば、横に回す・寄せられる・
 *    奪われる、がすべて「このゲームで実際に起きたこと」として入る。
 *
 * 🔴 規則（engine / constants / presets / training / model）を変えたら表は古くなる。
 *    `inputs` が今のファイルと一致しないと `npm run check` [12] が赤になる。
 */

export interface ValueTable {
  /** 攻める向きに測った x（自ゴール側が 0）の刻み・y の刻み（m） */
  cellX: number;
  cellY: number;
  nx: number;
  ny: number;
  /** values[ix * ny + iy]。セルの中心の値 */
  values: number[];
  /** 作ったときの規則のファイルの指紋（古くなっていないかの検査に使う） */
  inputs: string;
  /** 何試合から作ったか・何回目のくり返しか（記録用） */
  matches: number;
  iteration: number;
}

/**
 * 表の「ふつうの高さ」＝全セルの中央値。
 * 🔑 「持ち場を保つ」「持ち場を守る」などの一定値は、この高さの何倍かで決める（D-44）。
 *    数字で直に置くと、表を作り直して全体の高さが変わるたびに守備が緩んだり固まったりした。
 */
export function tableLevel(t: ValueTable): number {
  const sorted = [...t.values].sort((a, b) => a - b);
  return sorted[Math.floor(sorted.length / 2)]!;
}

