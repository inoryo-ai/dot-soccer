/**
 * 新エンジン（`src/sim/match/`）の数の道具（D-51）。
 *
 * 🔑 `hypot` は `Math.sqrt(x*x + y*y)`。掛け算・足し算・平方根は IEEE 754 で**正しく丸めると決まっている**ので、
 *    どの機械・どのブラウザでも同じ値になる（決定論・D-08）。
 * 🔴 `pymath.ts` の `hypot` は旧エンジンを Python 版と1ビットまで合わせるための写しで、1回が重い。
 *    新エンジンには Python 版が無いので使わない。1試合の計算の 36% がそれだった（2026-10-05 の計測）。
 *    `Math.hypot` は使わない（ブラウザによって最後のビットが違ってよいと仕様に書いてある）。
 *    ピッチの大きさ（100m 程度）では、2乗が溢れたり消えたりすることは無い。
 */
export function hypot(x: number, y: number): number {
  return Math.sqrt(x * x + y * y);
}
